// Regenerates MoltenTerm's macOS icons from the brand kit's symbol (#73), as Notulia does (scripts/gen-icons.sh):
// macOS lays every app icon on one grid (an 824x824 tile at (100,100) of a 1024 canvas), so the macOS icons are drawn
// on it rather than taken from the kit's full-size tile, which would look bigger than its neighbours in the Dock. The
// gold build has an icon of its own, a gold tile, so the app of every day cannot be taken for a dev build.
//
// usage: node scripts/moltenterm-gen-icons.mjs   (writes build/moltenterm/icon.icns and icon-gold.icns)

/* global Buffer, console, process */

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const Repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const Brand = path.join(Repo, "build", "moltenterm", "brand");

const Orange = "#FF7C0D";
const DarkTile = "#18181B";
const GoldInk = "#2E1F05";

// The kit's symbol spans 298 x 235 units; on the kit's 896 tile it is drawn at scale 2, centred.
const MarkWidth = 298;
const MarkHeight = 235;
const Tile = { x: 100, y: 100, size: 824, radius: 185.4 };
const MarkScale = (Tile.size / 896) * 2;
const MarkX = 512 - (MarkWidth * MarkScale) / 2;
// The kit sits the symbol 5 units below the tile's centre, optically; kept at the same proportion.
const MarkY = 512 + (5 * Tile.size) / 896 - (MarkHeight * MarkScale) / 2;

export function readMarkPath(markSvg) {
    const match = /<path[^>]*\sd="([^"]+)"/.exec(markSvg);
    if (!match) {
        throw new Error("no path in the brand symbol");
    }
    return match[1];
}

function markGroup(d, fill) {
    return `<g transform="translate(${MarkX.toFixed(2)} ${MarkY.toFixed(2)}) scale(${MarkScale.toFixed(5)})"><path fill="${fill}" d="${d}"/></g>`;
}

function tileRect(fill, extra = "") {
    return `<rect x="${Tile.x}" y="${Tile.y}" width="${Tile.size}" height="${Tile.size}" rx="${Tile.radius}" fill="${fill}"${extra}/>`;
}

export function macosIconSvg(d) {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024" role="img" aria-label="MoltenTerm application icon (macOS)">
  <!-- MoltenTerm's macOS icon, on Apple's grid. Generated by scripts/moltenterm-gen-icons.mjs from svg/mark.svg. -->
  ${tileRect(DarkTile)}
  ${markGroup(d, Orange)}
</svg>
`;
}

// The gold tile with a foil sheen and a glint, as Notulia's Gold (app-icon-macos-gold.svg).
export function macosGoldIconSvg(d) {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024" role="img" aria-label="MoltenTerm Gold application icon (macOS)">
  <!-- MoltenTerm Gold's macOS icon: the symbol on a gold tile, so the build of every day is told apart from dev
       builds in the Dock and Cmd-Tab. Generated by scripts/moltenterm-gen-icons.mjs from svg/mark.svg. -->
  <defs>
    <linearGradient id="gold" x1="100" y1="100" x2="924" y2="924" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#8A6317"/>
      <stop offset="0.22" stop-color="#D9A93F"/>
      <stop offset="0.46" stop-color="#FBE7A1"/>
      <stop offset="0.64" stop-color="#E0AF48"/>
      <stop offset="1" stop-color="#6F4A0E"/>
    </linearGradient>
    <linearGradient id="foil" x1="100" y1="924" x2="924" y2="100" gradientUnits="userSpaceOnUse">
      <stop offset="0.18" stop-color="#FF9FD6" stop-opacity="0"/>
      <stop offset="0.30" stop-color="#FF9FD6" stop-opacity="0.22"/>
      <stop offset="0.40" stop-color="#C6A8FF" stop-opacity="0.22"/>
      <stop offset="0.50" stop-color="#FFF6A6" stop-opacity="0.30"/>
      <stop offset="0.60" stop-color="#9FE7FF" stop-opacity="0.16"/>
      <stop offset="0.72" stop-color="#FF9FD6" stop-opacity="0.20"/>
      <stop offset="0.84" stop-color="#FF9FD6" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="glint" x1="100" y1="100" x2="924" y2="924" gradientUnits="userSpaceOnUse">
      <stop offset="0.30" stop-color="#FFFFFF" stop-opacity="0"/>
      <stop offset="0.38" stop-color="#FFFFFF" stop-opacity="0.55"/>
      <stop offset="0.44" stop-color="#FFFFFF" stop-opacity="0"/>
    </linearGradient>
    <clipPath id="tile">${tileRect("#000")}</clipPath>
  </defs>
  ${tileRect("url(#gold)")}
  <g clip-path="url(#tile)">
    <rect x="${Tile.x}" y="${Tile.y}" width="${Tile.size}" height="${Tile.size}" fill="url(#foil)"/>
    <rect x="${Tile.x}" y="${Tile.y}" width="${Tile.size}" height="${Tile.size}" fill="url(#glint)"/>
  </g>
  <rect x="106" y="106" width="812" height="812" rx="180" fill="none" stroke="#FFF3C4" stroke-opacity="0.55" stroke-width="12"/>
  ${markGroup(d, GoldInk)}
</svg>
`;
}

// The sizes macOS asks of an .icns, as iconutil names them.
const IconsetSizes = [
    ["icon_16x16.png", 16],
    ["icon_16x16@2x.png", 32],
    ["icon_32x32.png", 32],
    ["icon_32x32@2x.png", 64],
    ["icon_128x128.png", 128],
    ["icon_128x128@2x.png", 256],
    ["icon_256x256.png", 256],
    ["icon_256x256@2x.png", 512],
    ["icon_512x512.png", 512],
    ["icon_512x512@2x.png", 1024],
];

async function writeIcns(sharp, svg, icnsPath, pngPath) {
    const iconset = fs.mkdtempSync(path.join(os.tmpdir(), "moltenterm-icon-")) + ".iconset";
    fs.mkdirSync(iconset);
    for (const [name, size] of IconsetSizes) {
        await sharp(Buffer.from(svg), { density: 72 * (size / 1024) * 4 })
            .resize(size, size)
            .png()
            .toFile(path.join(iconset, name));
    }
    fs.copyFileSync(path.join(iconset, "icon_512x512@2x.png"), pngPath);
    execFileSync("iconutil", ["-c", "icns", "-o", icnsPath, iconset]);
    fs.rmSync(iconset, { recursive: true, force: true });
}

async function main() {
    let sharp;
    try {
        sharp = (await import("sharp")).default;
    } catch {
        console.error("sharp is needed to render the icons: run npm install first");
        process.exit(1);
    }
    const d = readMarkPath(fs.readFileSync(path.join(Brand, "svg", "mark.svg"), "utf8"));
    const normal = macosIconSvg(d);
    const gold = macosGoldIconSvg(d);
    fs.writeFileSync(path.join(Brand, "svg", "app-icon-macos.svg"), normal);
    fs.writeFileSync(path.join(Brand, "svg", "app-icon-macos-gold.svg"), gold);
    const out = path.join(Repo, "build", "moltenterm");
    await writeIcns(sharp, normal, path.join(out, "icon.icns"), path.join(Brand, "png", "app-icon-macos-1024.png"));
    await writeIcns(
        sharp,
        gold,
        path.join(out, "icon-gold.icns"),
        path.join(Brand, "png", "app-icon-macos-gold-1024.png")
    );
    console.log("icons written: build/moltenterm/icon.icns, build/moltenterm/icon-gold.icns");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
    await main();
}
