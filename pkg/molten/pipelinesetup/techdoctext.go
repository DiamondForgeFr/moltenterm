// docWords words the document in one language.
type docWords struct {
	lang string
}

// TechDocLangOf: the language the document is written in, from a declared language tag ("fr", "fr-FR", "FR").
func TechDocLangOf(declared string) string {
	tag := strings.ToLower(strings.TrimSpace(declared))
	if base, _, ok := strings.Cut(strings.ReplaceAll(tag, "_", "-"), "-"); ok {
		tag = base
	}
	if _, ok := techDocTexts[tag]; ok {
		return tag
	}
	return TechDocLangEn
}

func wordsOf(lang string) docWords {
	return docWords{lang: TechDocLangOf(lang)}
}

func (w docWords) s(key string) string {
	if text, ok := techDocTexts[w.lang][key]; ok {
		return text
	}
	return techDocTexts[TechDocLangEn][key]
}

func (w docWords) f(key string, args ...any) string {
	return fmt.Sprintf(w.s(key), args...)
}

// historyHeads: the history table's heading in every language, so an earlier document's rows are carried over
// whatever language it was written in.
func historyHeads() map[string]bool {
	rtn := map[string]bool{}
	for _, texts := range techDocTexts {
		rtn[texts["hist.head"]] = true
	}
	return rtn
}
