func TestVerifyStepsReadsTheHowToVerifyList(t *testing.T) {
	t.Parallel()
	body := "Resolves #12\n\n## Summary\n- not a step\n\n## How to verify\n\n1. Open the **loader** page\n" +
		"2. Click Start;\n   the dominoes turn\n- [ ] Stop it\n- [x] Read the log\n\n```sh\nnpm run dev\n```\n" +
		"## Behaviour change\n- not a step either\n"
	want := []string{"Open the loader page", "Click Start; the dominoes turn", "Stop it", "Read the log"}
	if got := verifySteps(body); !slices.Equal(got, want) {
		t.Fatalf("steps:\n got %q\nwant %q", got, want)
	}
}

func TestVerifyStepsHeadingsItKnows(t *testing.T) {
	t.Parallel()
	for _, heading := range []string{"### How to verify (Human Testing)", "**How to test**", "## Test plan:", "## Comment vérifier", "# À tester"} {
		body := heading + "\n- Open the page\n"
		if got := verifySteps(body); !slices.Equal(got, []string{"Open the page"}) {
			t.Errorf("%q: %q", heading, got)
		}
	}
	for _, heading := range []string{"## Tests", "## Testing", "## Summary", "## Verified by CI"} {
		if got := verifySteps(heading + "\n- go test ./...\n"); got != nil {
			t.Errorf("%q is not the developer's test: %q", heading, got)
		}
	}
	if got := verifySteps(""); got != nil {
		t.Fatalf("an empty body: %q", got)
	}
}

func TestVerifyStepsWithoutAListTakesTheFirstParagraph(t *testing.T) {
	t.Parallel()
	body := "## How to verify\n\nOpen the app and switch the theme.\nThe header follows.\n\nGenerated by an agent\n"
	want := []string{"Open the app and switch the theme.", "The header follows."}
	if got := verifySteps(body); !slices.Equal(got, want) {
		t.Fatalf("steps: %q", got)
	}
	if got := verifySteps("## How to verify\n---\n- after a rule\n"); got != nil {
		t.Fatalf("a rule ends the section: %q", got)
	}
}

func TestVerifyStepsAreBounded(t *testing.T) {
	t.Parallel()
	var b strings.Builder
	b.WriteString("## How to verify\n")
	for i := 0; i < 20; i++ {
		fmt.Fprintf(&b, "- step %d\n", i)
	}
	b.WriteString("- " + strings.Repeat("x", 400) + "\n")
	got := verifySteps(b.String())
	if len(got) != verifyMaxSteps || got[0] != "step 0" {
		t.Fatalf("steps: %d %q", len(got), got)
	}
	long := verifySteps("## How to verify\n- " + strings.Repeat("é", 400) + "\n")
	if len(long) != 1 || len([]rune(long[0])) != verifyMaxStepLen || !strings.HasSuffix(long[0], "…") {
		t.Fatalf("a long step is cut: %d", len([]rune(long[0])))
	}
}
