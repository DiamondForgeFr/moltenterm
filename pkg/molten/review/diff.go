const (
	// AC3: a side over 1 MB or 20,000 lines is collapsed until Load.
	LargeBytes = 1 << 20
	LargeLines = 20000
	// Load reads a file up to this size (the git runner's own output limit is 16 MB).
	MaxLoadBytes = 12 << 20

	// The paths one ls-tree or check-attr call names.
	pathChunk = 200
	// The file lists and the contents kept in memory: lists per (dir, base, head), contents by blob id.
	maxCachedLists   = 16
	maxCachedContent = 64 << 20
	// A file read sniffs its first lines for a generated-file header.
	headerLines = 6
)

const (
	StatusAdded       = "added"
	StatusModified    = "modified"
	StatusDeleted     = "deleted"
	StatusRenamed     = "renamed"
	StatusCopied      = "copied"
	StatusTypeChanged = "typechanged"

	CollapsedBinary    = "binary"
	CollapsedGenerated = "generated"
	CollapsedLarge     = "large"
	CollapsedSubmodule = "submodule"
)

const zeroOid = "0000000000000000000000000000000000000000"

// The lock files and generated files every project has under these names; the project marks its own with
// linguist-generated in .gitattributes (which also unmarks one of these with -linguist-generated).
var generatedNames = map[string]bool{
	"package-lock.json": true, "npm-shrinkwrap.json": true, "yarn.lock": true, "pnpm-lock.yaml": true,
	"bun.lock": true, "bun.lockb": true, "go.sum": true, "go.work.sum": true, "cargo.lock": true, "gemfile.lock": true,
	"poetry.lock": true, "pipfile.lock": true, "uv.lock": true, "composer.lock": true, "mix.lock": true,
	"pubspec.lock": true, "podfile.lock": true, "flake.lock": true, "packages.lock.json": true, "gotypes.d.ts": true,
}

var generatedSuffixes = []string{".pb.go", "_pb2.py", ".pb.ts", ".min.js", ".min.css", ".js.map", ".css.map", ".g.dart"}

// The header a code generator writes: Go's "Code generated … DO NOT EDIT." and the common "generated by".
var generatedHeaderRe = regexp.MustCompile(`(?i)(code generated\b.*\bdo not edit|^\W{0,4}(auto-?)?generated (by|from)\b|@generated\b)`)

// File is one changed file of the PR (AC1).
type File struct {
	Path      string `json:"path"`
	OldPath   string `json:"oldpath,omitempty"`
	Status    string `json:"status"`
	Additions int    `json:"additions"`
	Deletions int    `json:"deletions"`
	Binary    bool   `json:"binary,omitempty"`
	Generated bool   `json:"generated,omitempty"`
	// The blob ids of the two sides ("" for the side that does not exist), and their sizes in bytes.
	OldBlob string `json:"oldblob,omitempty"`
	NewBlob string `json:"newblob,omitempty"`
	OldSize int64  `json:"oldsize,omitempty"`
	NewSize int64  `json:"newsize,omitempty"`
	// Collapsed: why the file waits for Load (Collapsed…), "" when it opens directly.
	Collapsed string `json:"collapsed,omitempty"`
}

// FilesRequest names the diff: the PR's head against the merge base of its base branch (the three-dot diff GitHub
// shows), or, with From, the plain diff from an earlier head (the "since last round" view).
type FilesRequest struct {
	Dir     string `json:"dir"`
	HeadRef string `json:"headref"`
	BaseRef string `json:"baseref"`
	HeadOid string `json:"headoid,omitempty"`
	// BaseOid: the base branch's tip as GitHub has it (the PR's baseRefOid); empty, origin/<baseref>.
	BaseOid string `json:"baseoid,omitempty"`
	From    string `json:"from,omitempty"`
}

type FilesResult struct {
	HeadOid string `json:"headoid"`
	// BaseOid: the merge base, or From.
	BaseOid string `json:"baseoid"`
	From    string `json:"from,omitempty"`
	Files   []File `json:"files"`
	// Ms: how long git took, for NFR-REV-001.
	Ms     int64 `json:"ms"`
	Cached bool  `json:"cached,omitempty"`
}

// FileRequest reads one file's two sides by blob id. Without Load, a collapsed file returns no content.
type FileRequest struct {
	Dir     string `json:"dir"`
	Path    string `json:"path"`
	OldBlob string `json:"oldblob,omitempty"`
	NewBlob string `json:"newblob,omitempty"`
	Load    bool   `json:"load,omitempty"`
}

type FileResult struct {
	Path     string `json:"path"`
	Original string `json:"original"`
	Modified string `json:"modified"`
	// Collapsed: the content was not sent (CollapsedLarge or CollapsedGenerated found on reading, or a binary file).
	Collapsed string `json:"collapsed,omitempty"`
	OldLines  int    `json:"oldlines,omitempty"`
	NewLines  int    `json:"newlines,omitempty"`
	// Binary: a side is not text; nothing is shown as text.
	Binary bool `json:"binary,omitempty"`
	// Hunks: the hunks of the diff GitHub shows, where a line comment can go (FR-REV-003 AC4).
	Hunks []Hunk `json:"hunks,omitempty"`
	Ms    int64  `json:"ms"`
}

// CompareRequest asks how far the PR's head moved since the head the tab shows.
type CompareRequest struct {
	Dir     string `json:"dir"`
	HeadRef string `json:"headref"`
	From    string `json:"from"`
	To      string `json:"to"`
}

type CompareResult struct {
	Commits int `json:"commits"`
	// Rewritten: the old head is not in the new one's history (a rebase or a force push).
	Rewritten bool `json:"rewritten,omitempty"`
}

// Differ computes the diffs and keeps them in memory.
type Differ struct {
	git reviewsession.GitRunner
	now func() time.Time

	lock         sync.Mutex
	lists        map[string]FilesResult
	listOrder    []string
	content      map[string]string
	contentOrder []string
	contentBytes int
}

func MakeDiffer(git reviewsession.GitRunner) *Differ {
	return &Differ{git: git, now: time.Now, lists: map[string]FilesResult{}, content: map[string]string{}}
}

func (d *Differ) cachedList(key string) (FilesResult, bool) {
	d.lock.Lock()
	defer d.lock.Unlock()
	rtn, ok := d.lists[key]
	return rtn, ok
}

func (d *Differ) keepList(key string, result FilesResult) {
	d.lock.Lock()
	defer d.lock.Unlock()
	if _, ok := d.lists[key]; !ok {
		d.listOrder = append(d.listOrder, key)
	}
	d.lists[key] = result
	for len(d.listOrder) > maxCachedLists {
		delete(d.lists, d.listOrder[0])
		d.listOrder = d.listOrder[1:]
	}
}

func (d *Differ) cachedContent(oid string) (string, bool) {
	d.lock.Lock()
	defer d.lock.Unlock()
	rtn, ok := d.content[oid]
	return rtn, ok
}

// keepContent caches a blob's text: a blob id names one content forever, so nothing invalidates it.
func (d *Differ) keepContent(oid string, text string) {
	if len(text) > maxCachedContent/4 {
		return
	}
	d.lock.Lock()
	defer d.lock.Unlock()
	if _, ok := d.content[oid]; ok {
		return
	}
	d.content[oid] = text
	d.contentOrder = append(d.contentOrder, oid)
	d.contentBytes += len(text)
	for d.contentBytes > maxCachedContent && len(d.contentOrder) > 0 {
		old := d.contentOrder[0]
		d.contentOrder = d.contentOrder[1:]
		d.contentBytes -= len(d.content[old])
		delete(d.content, old)
	}
}

func checkDir(dir string) error {
	if dir == "" || !filepath.IsAbs(dir) {
		return fmt.Errorf("dir must be the project's absolute folder")
	}
	return nil
}

func isOid(s string) bool {
	return reviewsession.IsOid(s)
}

func checkOid(oid string, what string) error {
	if oid != "" && !reviewsession.IsOid(oid) {
		return fmt.Errorf("%s is not a commit id", what)
	}
	return nil
}

func (d *Differ) hasCommit(ctx context.Context, dir string, oid string) bool {
	_, err := d.git(ctx, dir, "cat-file", "-e", oid+"^{commit}")
	return err == nil
}

// baseTip is the base branch's tip: GitHub's (fetched once when the project lacks it), else origin's, else the local
// branch.
func (d *Differ) baseTip(ctx context.Context, req FilesRequest) (string, error) {
	if req.BaseOid != "" {
		if d.hasCommit(ctx, req.Dir, req.BaseOid) {
			return req.BaseOid, nil
		}
		d.git(ctx, req.Dir, "fetch", "--quiet", "--no-tags", "origin", "refs/heads/"+req.BaseRef)
		if d.hasCommit(ctx, req.Dir, req.BaseOid) {
			return req.BaseOid, nil
		}
	}
	for _, ref := range []string{"refs/remotes/origin/" + req.BaseRef, "refs/heads/" + req.BaseRef} {
		out, err := d.git(ctx, req.Dir, "rev-parse", "--verify", "--quiet", ref+"^{commit}")
		if oid := strings.TrimSpace(string(out)); err == nil && reviewsession.IsOid(oid) {
			return oid, nil
		}
	}
	return "", fmt.Errorf("the base branch %s was not found in the project or on origin", req.BaseRef)
}

// MergeBase is the merge base of the head with the base branch's tip (DS-REV-002).
func (d *Differ) MergeBase(ctx context.Context, req FilesRequest, head string) (string, error) {
	tip, err := d.baseTip(ctx, req)
	if err != nil {
		return "", err
	}
	out, err := d.git(ctx, req.Dir, "merge-base", tip, head)
	oid := strings.TrimSpace(string(out))
	if err != nil || !reviewsession.IsOid(oid) {
		return "", fmt.Errorf("the merge base of %s and the PR's head could not be read: %v", req.BaseRef, err)
	}
	return oid, nil
}

func checkFilesRequest(req FilesRequest) error {
	if err := checkDir(req.Dir); err != nil {
		return err
	}
	if !reviewsession.ValidRef(req.HeadRef) {
		return fmt.Errorf("headref must be the PR's head branch")
	}
	if !reviewsession.ValidRef(req.BaseRef) {
		return fmt.Errorf("baseref must be the PR's base branch")
	}
	if err := checkOid(req.HeadOid, "headoid"); err != nil {
		return err
	}
	if err := checkOid(req.BaseOid, "baseoid"); err != nil {
		return err
	}
	return checkOid(req.From, "from")
}

// Files lists the PR's changed files (AC1, AC3): one raw and one numstat diff, the sizes from ls-tree and the
// linguist-generated attribute from check-attr, a few paths per call.
func (d *Differ) Files(ctx context.Context, req FilesRequest) (FilesResult, error) {
	if err := checkFilesRequest(req); err != nil {
		return FilesResult{}, err
	}
	started := d.now()
	head, err := reviewsession.ResolveHead(ctx, d.git, req.Dir, req.HeadRef, req.HeadOid)
	if err != nil {
		return FilesResult{}, err
	}
	base := req.From
	if base != "" && !d.hasCommit(ctx, req.Dir, base) {
		return FilesResult{}, fmt.Errorf("the earlier head %s is not in the project any more", shortOid(base))
	}
	key := req.Dir + "\x00" + base + "\x00" + head
	if base == "" {
		key = req.Dir + "\x00" + req.BaseRef + "\x00" + req.BaseOid + "\x00" + head
	}
	if cached, ok := d.cachedList(key); ok {
		cached.Cached = true
		cached.Ms = d.now().Sub(started).Milliseconds()
		return cached, nil
	}
	if base == "" {
		base, err = d.MergeBase(ctx, req, head)
		if err != nil {
			return FilesResult{}, err
		}
	}
	files, err := d.listFiles(ctx, req.Dir, base, head)
	if err != nil {
		return FilesResult{}, err
	}
	result := FilesResult{HeadOid: head, BaseOid: base, From: req.From, Files: files, Ms: d.now().Sub(started).Milliseconds()}
	d.keepList(key, result)
	return result, nil
}

func (d *Differ) listFiles(ctx context.Context, dir string, base string, head string) ([]File, error) {
	raw, err := d.git(ctx, dir, "diff", "--raw", "--no-abbrev", "-z", "-M", "--no-ext-diff", "--no-textconv", base, head)
	if err != nil {
		return nil, fmt.Errorf("the PR's files could not be listed: %w", err)
	}
	files := ParseRaw(raw)
	if len(files) == 0 {
		return []File{}, nil
	}
	oldPaths, newPaths := []string{}, []string{}
	for _, f := range files {
		if f.OldBlob != "" {
			oldPaths = append(oldPaths, f.oldSidePath())
		}
		if f.NewBlob != "" {
			newPaths = append(newPaths, f.Path)
		}
	}
	// The counts, the sizes and the attributes are independent reads: they run together (NFR-REV-001).
	var counts []byte
	var oldSizes, newSizes map[string]int64
	var generated map[string]bool
	var wg sync.WaitGroup
	wg.Add(4)
	go func() {
		defer wg.Done()
		counts, _ = d.git(ctx, dir, "diff", "--numstat", "-z", "-M", "--no-ext-diff", "--no-textconv", base, head)
	}()
	go func() {
		defer wg.Done()
		oldSizes = d.sizes(ctx, dir, base, oldPaths)
	}()
	go func() {
		defer wg.Done()
		newSizes = d.sizes(ctx, dir, head, newPaths)
	}()
	go func() {
		defer wg.Done()
		generated = d.linguistGenerated(ctx, dir, head, newPaths)
	}()
	wg.Wait()
	ApplyNumstat(files, counts)
	for i := range files {
		f := &files[i]
		f.OldSize = oldSizes[f.oldSidePath()]
		f.NewSize = newSizes[f.Path]
		if f.OldBlob == "" {
			f.OldSize = 0
		}
		if f.NewBlob == "" {
			f.NewSize = 0
		}
		f.Generated = IsGeneratedName(f.Path)
		if attr, ok := generated[f.Path]; ok {
			f.Generated = attr
		}
		f.Collapsed = collapsedOf(*f)
	}
	sort.SliceStable(files, func(i, j int) bool { return files[i].Path < files[j].Path })
	return files, nil
}

func (f File) oldSidePath() string {
	if f.OldPath != "" {
		return f.OldPath
	}
	return f.Path
}

// collapsedOf is AC3's rule as far as the list knows it: binary, generated, or large by size or by its changed lines
// (an added or deleted file's lines are its additions or deletions). A modified file over 20,000 lines with few changes
// is found when it is read.
func collapsedOf(f File) string {
	switch {
	case f.Status == CollapsedSubmodule:
		return CollapsedSubmodule
	case f.Binary:
		return CollapsedBinary
	case f.Generated:
		return CollapsedGenerated
	case f.OldSize > LargeBytes || f.NewSize > LargeBytes || f.Additions > LargeLines || f.Deletions > LargeLines:
		return CollapsedLarge
	}
	return ""
}

// IsGeneratedName: lock files and generated files known by their name.
func IsGeneratedName(p string) bool {
	base := strings.ToLower(path.Base(p))
	if generatedNames[base] {
		return true
	}
	for _, suffix := range generatedSuffixes {
		if strings.HasSuffix(base, suffix) {
			return true
		}
	}
	return false
}

func splitZ(out []byte) []string {
	text := strings.TrimSuffix(string(out), "\x00")
	if text == "" {
		return nil
	}
	return strings.Split(text, "\x00")
}

func blobOf(oid string) string {
	if oid == "" || oid == zeroOid || strings.Trim(oid, "0") == "" {
		return ""
	}
	return oid
}

// ParseRaw reads `git diff --raw --no-abbrev -z`: ":oldmode newmode oldoid newoid status\0path\0", with two paths for a
// rename or a copy.
func ParseRaw(out []byte) []File {
	fields := splitZ(out)
	var rtn []File
	for i := 0; i < len(fields); i++ {
		head := fields[i]
		if !strings.HasPrefix(head, ":") {
			continue
		}
		parts := strings.Fields(strings.TrimPrefix(head, ":"))
		if len(parts) < 5 || i+1 >= len(fields) {
			continue
		}
		oldMode, newMode, status := parts[0], parts[1], parts[4]
		f := File{OldBlob: blobOf(parts[2]), NewBlob: blobOf(parts[3])}
		switch status[0] {
		case 'A':
			f.Status = StatusAdded
		case 'D':
			f.Status = StatusDeleted
		case 'R':
			f.Status = StatusRenamed
		case 'C':
			f.Status = StatusCopied
		case 'T':
			f.Status = StatusTypeChanged
		default:
			f.Status = StatusModified
		}
		if (status[0] == 'R' || status[0] == 'C') && i+2 < len(fields) {
			f.OldPath, f.Path = fields[i+1], fields[i+2]
			i += 2
		} else {
			f.Path = fields[i+1]
			i++
		}
		// A submodule's "blob" is a commit of another repository: nothing to read here.
		if oldMode == "160000" || newMode == "160000" {
			f.Status = CollapsedSubmodule
			f.OldBlob, f.NewBlob = "", ""
		}
		rtn = append(rtn, f)
	}
	return rtn
}

// ApplyNumstat adds `git diff --numstat -z` counts: "add\tdel\tpath\0", or "add\tdel\t\0old\0new\0" for a rename;
// "-\t-" is a binary file.
func ApplyNumstat(files []File, out []byte) {
	byPath := map[string]*File{}
	for i := range files {
		byPath[files[i].Path] = &files[i]
	}
	fields := splitZ(out)
	for i := 0; i < len(fields); i++ {
		parts := strings.SplitN(fields[i], "\t", 3)
		if len(parts) != 3 {
			continue
		}
		p := parts[2]
		if p == "" && i+2 < len(fields) {
			p = fields[i+2]
			i += 2
		}
		f := byPath[p]
		if f == nil {
			continue
		}
		if parts[0] == "-" {
			f.Binary = true
			continue
		}
		f.Additions, _ = strconv.Atoi(parts[0])
		f.Deletions, _ = strconv.Atoi(parts[1])
	}
}

// sizes reads the blob sizes of paths at a commit with ls-tree -l.
func (d *Differ) sizes(ctx context.Context, dir string, commit string, paths []string) map[string]int64 {
	rtn := map[string]int64{}
	for start := 0; start < len(paths); start += pathChunk {
		chunk := paths[start:min(start+pathChunk, len(paths))]
		args := append([]string{"--literal-pathspecs", "ls-tree", "-l", "-z", "--full-tree", commit, "--"}, chunk...)
		out, err := d.git(ctx, dir, args...)
		if err != nil {
			continue
		}
		for p, size := range ParseLsTreeSizes(out) {
			rtn[p] = size
		}
	}
	return rtn
}

// ParseLsTreeSizes reads `git ls-tree -l -z`: "mode type oid size\tpath\0".
func ParseLsTreeSizes(out []byte) map[string]int64 {
	rtn := map[string]int64{}
	for _, entry := range splitZ(out) {
		meta, p, ok := strings.Cut(entry, "\t")
		if !ok {
			continue
		}
		parts := strings.Fields(meta)
		if len(parts) < 4 {
			continue
		}
		size, err := strconv.ParseInt(parts[3], 10, 64)
		if err != nil {
			continue
		}
		rtn[p] = size
	}
	return rtn
}

// linguistGenerated reads the linguist-generated attribute of paths at the head (.gitattributes as the PR has it):
// true for set, false for unset (-linguist-generated or linguist-generated=false), absent when unspecified.
func (d *Differ) linguistGenerated(ctx context.Context, dir string, head string, paths []string) map[string]bool {
	rtn := map[string]bool{}
	for start := 0; start < len(paths); start += pathChunk {
		chunk := paths[start:min(start+pathChunk, len(paths))]
		args := append([]string{"check-attr", "-z", "--source", head, "linguist-generated", "--"}, chunk...)
		out, err := d.git(ctx, dir, args...)
		if err != nil {
			// git before 2.40 has no --source: the name rules stay.
			return rtn
		}
		for p, v := range ParseCheckAttr(out) {
			rtn[p] = v
		}
	}
	return rtn
}

// ParseCheckAttr reads `git check-attr -z`: "path\0attr\0value\0".
func ParseCheckAttr(out []byte) map[string]bool {
	rtn := map[string]bool{}
	fields := splitZ(out)
	for i := 0; i+2 < len(fields); i += 3 {
		switch strings.ToLower(fields[i+2]) {
		case "set", "true":
			rtn[fields[i]] = true
		case "unset", "false":
			rtn[fields[i]] = false
		}
	}
	return rtn
}

func checkFileRequest(req FileRequest) error {
	if err := checkDir(req.Dir); err != nil {
		return err
	}
	if req.Path == "" {
		return fmt.Errorf("path is required")
	}
	if req.OldBlob == "" && req.NewBlob == "" {
		return fmt.Errorf("the file has no side to read")
	}
	if err := checkOid(req.OldBlob, "oldblob"); err != nil {
		return err
	}
	return checkOid(req.NewBlob, "newblob")
}

func (d *Differ) blob(ctx context.Context, dir string, oid string) (string, error) {
	if oid == "" {
		return "", nil
	}
	if text, ok := d.cachedContent(oid); ok {
		return text, nil
	}
	out, err := d.git(ctx, dir, "cat-file", "blob", oid)
	if err != nil {
		return "", fmt.Errorf("the file could not be read: %w", err)
	}
	text := string(out)
	d.keepContent(oid, text)
	return text, nil
}

func (d *Differ) blobSize(ctx context.Context, dir string, oid string) int64 {
	if oid == "" {
		return 0
	}
	if text, ok := d.cachedContent(oid); ok {
		return int64(len(text))
	}
	out, err := d.git(ctx, dir, "cat-file", "-s", oid)
	if err != nil {
		return 0
	}
	size, _ := strconv.ParseInt(strings.TrimSpace(string(out)), 10, 64)
	return size
}

func countLines(text string) int {
	if text == "" {
		return 0
	}
	n := strings.Count(text, "\n")
	if !strings.HasSuffix(text, "\n") {
		n++
	}
	return n
}

// LooksGenerated: the first lines carry a code generator's header.
func LooksGenerated(text string) bool {
	lines := strings.SplitN(text, "\n", headerLines+1)
	for i, line := range lines {
		if i >= headerLines {
			break
		}
		if generatedHeaderRe.MatchString(line) {
			return true
		}
	}
	return false
}

func isText(text string) bool {
	return utf8.ValidString(text) && !strings.ContainsRune(text, 0)
}

// File reads one file's two sides (AC2, AC4). Without Load, a side found large or generated on reading is not sent.
func (d *Differ) File(ctx context.Context, req FileRequest) (FileResult, error) {
	if err := checkFileRequest(req); err != nil {
		return FileResult{}, err
	}
	started := d.now()
	rtn := FileResult{Path: req.Path}
	if max(d.blobSize(ctx, req.Dir, req.OldBlob), d.blobSize(ctx, req.Dir, req.NewBlob)) > MaxLoadBytes {
		rtn.Collapsed = CollapsedLarge
		rtn.Ms = d.now().Sub(started).Milliseconds()
		return rtn, nil
	}
	original, err := d.blob(ctx, req.Dir, req.OldBlob)
	if err != nil {
		return FileResult{}, err
	}
	modified, err := d.blob(ctx, req.Dir, req.NewBlob)
	if err != nil {
		return FileResult{}, err
	}
	rtn.OldLines, rtn.NewLines = countLines(original), countLines(modified)
	rtn.Ms = d.now().Sub(started).Milliseconds()
	if !isText(original) || !isText(modified) {
		rtn.Binary, rtn.Collapsed = true, CollapsedBinary
		return rtn, nil
	}
	if !req.Load {
		switch {
		case max(len(original), len(modified)) > LargeBytes || max(rtn.OldLines, rtn.NewLines) > LargeLines:
			rtn.Collapsed = CollapsedLarge
			return rtn, nil
		case LooksGenerated(modified) || (req.NewBlob == "" && LooksGenerated(original)):
			rtn.Collapsed = CollapsedGenerated
			return rtn, nil
		}
	}
	rtn.Original, rtn.Modified = original, modified
	rtn.Hunks = d.hunks(ctx, req, rtn.OldLines, rtn.NewLines)
	return rtn, nil
}

// Compare counts the commits the PR's head gained since the head the tab shows (AC5); the new head is fetched when
// the project lacks it.
func (d *Differ) Compare(ctx context.Context, req CompareRequest) (CompareResult, error) {
	if err := checkDir(req.Dir); err != nil {
		return CompareResult{}, err
	}
	if !reviewsession.ValidRef(req.HeadRef) || !reviewsession.IsOid(req.From) || !reviewsession.IsOid(req.To) {
		return CompareResult{}, fmt.Errorf("headref, from and to must be the PR's branch and two commit ids")
	}
	if req.From == req.To {
		return CompareResult{}, nil
	}
	to, err := reviewsession.ResolveHead(ctx, d.git, req.Dir, req.HeadRef, req.To)
	if err != nil {
		return CompareResult{}, err
	}
	out, err := d.git(ctx, req.Dir, "rev-list", "--count", req.From+".."+to)
	if err != nil {
		return CompareResult{}, fmt.Errorf("the new commits could not be counted: %w", err)
	}
	count, _ := strconv.Atoi(strings.TrimSpace(string(out)))
	_, ancestorErr := d.git(ctx, req.Dir, "merge-base", "--is-ancestor", req.From, to)
	return CompareResult{Commits: count, Rewritten: ancestorErr != nil}, nil
}

func shortOid(oid string) string {
	if len(oid) > 12 {
		return oid[:12]
	}
	return oid
}
