func TestParseRaw(t *testing.T) {
	a := strings.Repeat("a", 40)
	b := strings.Repeat("b", 40)
	raw := ":100644 100644 " + a + " " + b + " M\x00src/x.go\x00" +
		":000000 100644 " + zeroOid + " " + b + " A\x00new.txt\x00" +
		":100644 000000 " + a + " " + zeroOid + " D\x00old.txt\x00" +
		":100644 100644 " + a + " " + b + " R087\x00from/y.ts\x00to/y.ts\x00" +
		":160000 160000 " + a + " " + b + " M\x00vendor/sub\x00"
	files := ParseRaw([]byte(raw))
	if len(files) != 5 {
		t.Fatalf("files: %+v", files)
	}
	if files[0].Status != StatusModified || files[0].OldBlob != a || files[0].NewBlob != b {
		t.Errorf("modified: %+v", files[0])
	}
	if files[1].Status != StatusAdded || files[1].OldBlob != "" || files[1].NewBlob != b {
		t.Errorf("added: %+v", files[1])
	}
	if files[2].Status != StatusDeleted || files[2].NewBlob != "" {
		t.Errorf("deleted: %+v", files[2])
	}
	if files[3].Status != StatusRenamed || files[3].OldPath != "from/y.ts" || files[3].Path != "to/y.ts" {
		t.Errorf("renamed: %+v", files[3])
	}
	if files[4].Status != CollapsedSubmodule || files[4].NewBlob != "" {
		t.Errorf("submodule: %+v", files[4])
	}
}

